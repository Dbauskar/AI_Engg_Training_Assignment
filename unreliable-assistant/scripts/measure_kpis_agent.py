"""Measure the agent-level KPIs that had no data: 14, 15, 17, 18, 19, 25, 27, 30 (+36 from load_tests/soak.py output).
  uv run python scripts/measure_kpis_agent.py [--skip-http]
Merges into evals/results/kpi_extra.json. Every number is from the LOCAL in-memory stack with a SYNTHETIC workload written here;
definitions are in each block. KPI-29 (cost per 1,000 queries) is deliberately NOT produced: no LLM is configured (extractive answerer),
so there are no billed tokens to price, and a compute-only figure would pass a cost target that was never about compute."""
